"""Offline, externally hash-pinned macOS freeze inputs and runtime versions."""
import hashlib
import importlib.metadata
import json
from pathlib import Path
import platform
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))

VERSIONS = {'PyInstaller': '6.16.0', 'pyusb': '1.3.1', 'pycryptodome': '3.23.0',
            'certifi': '2026.2.25', 'platformdirs': '4.2.2',
            'pyinstaller-hooks-contrib': '2025.9', 'packaging': '25.0',
            'altgraph': '0.17.4', 'macholib': '1.16.3'}


def verify(root, lock, expected):
    import tkinter
    from macos_release import check_notices
    check_notices(Path(root).resolve())
    root, prefix = Path(root).resolve(), Path(sys.base_prefix).resolve()
    raw = Path(lock).read_bytes()
    if len(expected) != 64 or hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError('macOS input lock SHA256 mismatch')
    manifest = json.loads(raw)
    if platform.python_version() != '3.12.10' or tkinter.TkVersion < 8.6:
        raise ValueError('Use python.org framework CPython 3.12.10 with Tk >= 8.6')
    if 'Python.framework' not in str(prefix) or sys.prefix != sys.base_prefix:
        raise ValueError('Use a dedicated, non-venv python.org framework build interpreter')
    for name, version in VERSIONS.items():
        if importlib.metadata.version(name) != version:
            raise ValueError('Wrong build dependency: ' + name + '==' + version)
    roots = {'repo': root, 'python': prefix}
    recorded = set()
    for group, records in manifest.items():
        if group not in roots or not isinstance(records, dict):
            raise ValueError('Input lock groups must be repo and python')
        for name, digest in records.items():
            path = (roots[group] / name).resolve()
            if not path.is_relative_to(roots[group]) or not path.is_file():
                raise ValueError('Invalid input: ' + name)
            if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                raise ValueError('Input hash mismatch: ' + name)
            recorded.add((group, path))
    # Pin the complete Python installation, including installed build/runtime modules,
    # Tcl/Tk, shared libraries and bootloaders; generated bytecode is not an input.
    required = {('python', p.resolve()) for p in prefix.rglob('*')
                if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'}
    tag = 'macos-' + platform.machine()
    for folder in ('diskos_installer', 'payload', 'flash', 'build', 'licenses',
                   'corresponding-source', 'src', 'spl-src', 'ui', 'vendor/' + tag):
        required |= {('repo', p.resolve()) for p in (root / folder).rglob('*')
                     if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'
                     and not p.is_relative_to(root / 'build/dist')}
    required |= {('repo', root / n) for n in ('LICENSE', 'NOTICE.md', 'README.md', 'SPL_SOURCE.md', 'requirements.txt',
                                                    'docs/INSTALL.md', 'docs/MACOS_RECOVERY.txt')}
    if not required <= recorded:
        raise ValueError('Input lock is incomplete: ' + str(sorted(str(p) for _, p in required - recorded)[:5]))
    return manifest


if __name__ == '__main__':
    verify(*sys.argv[1:])
